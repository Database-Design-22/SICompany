
DROP DATABASE IF EXISTS si_company;
CREATE DATABASE si_company DEFAULT CHARACTER SET utf8mb4;
USE si_company;
SET NAMES utf8mb4;

-- 부서
CREATE TABLE TB_DEPT (
  DEPT_ID            VARCHAR(10)    NOT NULL COMMENT '부서ID',
  DEPT_NM            VARCHAR(30)    NOT NULL COMMENT '부서명',
  CONSTRAINT pk_dept PRIMARY KEY (DEPT_ID),
  CONSTRAINT uq_dept_dept_nm UNIQUE (DEPT_NM)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='부서';

-- 권한
CREATE TABLE TB_AUTH (
  AUTH_ID            VARCHAR(10)    NOT NULL COMMENT '권한ID',
  AUTH_NM            VARCHAR(20)    NOT NULL COMMENT '권한명',
  CONSTRAINT pk_auth PRIMARY KEY (AUTH_ID),
  CONSTRAINT uq_auth_auth_nm UNIQUE (AUTH_NM)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='권한';

-- 기술등급
CREATE TABLE TB_SKILL_GRD (
