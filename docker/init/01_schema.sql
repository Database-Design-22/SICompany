  CONSTRAINT uq_eval_item_eval_item_nm UNIQUE (EVAL_ITEM_NM)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='평가항목';

-- 발주처
CREATE TABLE TB_CLIENT (
  CLIENT_ID          INT            NOT NULL AUTO_INCREMENT COMMENT '발주처ID',
  CLIENT_NM          VARCHAR(100)   NOT NULL COMMENT '발주처명',
  CONSTRAINT pk_client PRIMARY KEY (CLIENT_ID)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='발주처';

-- 합격자
CREATE TABLE TB_PASSER (
  PASSER_ID          INT            NOT NULL AUTO_INCREMENT COMMENT '합격자ID',
  PASSER_NM          VARCHAR(50)    NOT NULL COMMENT '합격자명',
  RRN                VARCHAR(255)   NOT NULL COMMENT '주민등록번호',
  JOBGRP             VARCHAR(10)    NOT NULL COMMENT '직군',
  DEPT_ID            VARCHAR(10)    NULL COMMENT '부서ID',
  CONSTRAINT pk_passer PRIMARY KEY (PASSER_ID),
  CONSTRAINT uq_passer_rrn UNIQUE (RRN),
  CONSTRAINT fk_passer_dept FOREIGN KEY (DEPT_ID) REFERENCES TB_DEPT (DEPT_ID),
  CONSTRAINT ck_passer_jobgrp CHECK (JOBGRP IN ('개발','비개발')),
  CONSTRAINT ck_passer_dept CHECK ((JOBGRP = '개발' AND DEPT_ID IS NULL) OR (JOBGRP = '비개발' AND DEPT_ID IS NOT NULL))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='합격자';

-- 직원 (슈퍼타입)
CREATE TABLE TB_EMP (
  EMP_ID             CHAR(7)        NOT NULL COMMENT '직원ID',
  RRN                VARCHAR(255)   NULL COMMENT '주민등록번호',
  EMP_NM             VARCHAR(50)    NULL COMMENT '직원명',
  LOGIN_ID           VARCHAR(30)    NOT NULL COMMENT '로그인ID',
  PWD                VARCHAR(255)   NOT NULL COMMENT '비밀번호',
  HIRE_DT            DATE           NOT NULL COMMENT '입사일자',
  EMP_DIV            VARCHAR(10)    NOT NULL COMMENT '직원구분',
  ENG_NM             VARCHAR(100)   NULL COMMENT '영문이름',
  LAST_EDU           VARCHAR(20)    NOT NULL COMMENT '최종학력',
  TELNO              VARCHAR(20)    NULL COMMENT '전화번호',
  ADDR               VARCHAR(200)   NULL COMMENT '주소',
  EMPL_STAT          VARCHAR(10)    NOT NULL COMMENT '재직상태',
  RTR_DT             DATE           NULL COMMENT '퇴사일자',
  DSTR_DT            DATE           NULL COMMENT '파기일자',
  AUTH_ID            VARCHAR(10)    NOT NULL DEFAULT 'EMP' COMMENT '권한ID',
  CONSTRAINT pk_emp PRIMARY KEY (EMP_ID),
  CONSTRAINT uq_emp_rrn UNIQUE (RRN),
  CONSTRAINT uq_emp_login_id UNIQUE (LOGIN_ID),
  CONSTRAINT fk_emp_auth FOREIGN KEY (AUTH_ID) REFERENCES TB_AUTH (AUTH_ID),
  CONSTRAINT ck_emp_div CHECK (EMP_DIV IN ('개발','비개발')),
  CONSTRAINT ck_emp_stat CHECK (EMPL_STAT IN ('재직','퇴사')),
  CONSTRAINT ck_emp_rtr CHECK (((EMPL_STAT = '재직' AND RTR_DT IS NULL) OR (EMPL_STAT = '퇴사' AND RTR_DT IS NOT NULL)) AND (RTR_DT IS NULL OR RTR_DT >= HIRE_DT)),
  CONSTRAINT ck_emp_pii CHECK (DSTR_DT IS NOT NULL OR (EMP_NM IS NOT NULL AND RRN IS NOT NULL)),
  CONSTRAINT ck_emp_dstr CHECK (DSTR_DT IS NULL OR (EMPL_STAT = '퇴사' AND DSTR_DT >= RTR_DT))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='직원 (슈퍼타입)';

-- 비개발직원
CREATE TABLE TB_NDEV_EMP (
  EMP_ID             CHAR(7)        NOT NULL COMMENT '직원ID',
  DEPT_ID            VARCHAR(10)    NOT NULL COMMENT '부서ID',
  CONSTRAINT pk_ndev_emp PRIMARY KEY (EMP_ID),
  CONSTRAINT fk_ndev_emp FOREIGN KEY (EMP_ID) REFERENCES TB_EMP (EMP_ID),
  CONSTRAINT fk_ndev_dept FOREIGN KEY (DEPT_ID) REFERENCES TB_DEPT (DEPT_ID)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='비개발직원';

-- 개발직원
CREATE TABLE TB_DEV_EMP (
