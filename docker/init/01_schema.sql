-- 평가 (슈퍼타입)
CREATE TABLE TB_EVAL (
  EVAL_ID            INT            NOT NULL AUTO_INCREMENT COMMENT '평가ID',
  EVAL_DIV           VARCHAR(10)    NOT NULL COMMENT '평가구분',
  EVAL_STAT          VARCHAR(10)    NOT NULL DEFAULT '작성중' COMMENT '평가상태',
  EVAL_DT            DATE           NULL COMMENT '평가일자',
  EVLTE_EMP_ID       CHAR(7)        NOT NULL COMMENT '피평가자직원ID',
  PRJ_ID             CHAR(7)        NOT NULL COMMENT '프로젝트ID',
  CONSTRAINT pk_eval PRIMARY KEY (EVAL_ID),
  CONSTRAINT uq_eval_prj UNIQUE (EVAL_ID, PRJ_ID),
  CONSTRAINT fk_eval_ptcp FOREIGN KEY (EVLTE_EMP_ID, PRJ_ID) REFERENCES TB_PRJ_PTCP (EMP_ID, PRJ_ID),
  CONSTRAINT ck_eval_div CHECK (EVAL_DIV IN ('PM','동료','고객')),
  CONSTRAINT ck_eval_stat CHECK (EVAL_STAT IN ('작성중','제출')),
  CONSTRAINT ck_eval_dt CHECK ((EVAL_STAT = '작성중' AND EVAL_DT IS NULL) OR (EVAL_STAT = '제출' AND EVAL_DT IS NOT NULL))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='평가 (슈퍼타입)';

