  GRD_ID             VARCHAR(10)    NULL COMMENT '등급ID',
  CONSTRAINT pk_dev_emp PRIMARY KEY (EMP_ID),
  CONSTRAINT fk_dev_emp FOREIGN KEY (EMP_ID) REFERENCES TB_EMP (EMP_ID),
  CONSTRAINT fk_dev_grd FOREIGN KEY (GRD_ID) REFERENCES TB_SKILL_GRD (GRD_ID)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='개발직원';

-- 보유기술
CREATE TABLE TB_HOLD_SKILL (
  SKILL_ID           INT            NOT NULL COMMENT '기술ID',
  EMP_ID             CHAR(7)        NOT NULL COMMENT '직원ID',
  CONSTRAINT pk_hold_skill PRIMARY KEY (SKILL_ID, EMP_ID),
  CONSTRAINT fk_hold_skill FOREIGN KEY (SKILL_ID) REFERENCES TB_SKILL (SKILL_ID),
  CONSTRAINT fk_hold_emp FOREIGN KEY (EMP_ID) REFERENCES TB_DEV_EMP (EMP_ID)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='보유기술';

-- 발주처담당자
CREATE TABLE TB_CLIENT_MGR (
  CLIENT_ID          INT            NOT NULL COMMENT '발주처ID',
  MGR_ID             INT            NOT NULL COMMENT '담당자ID',
  MGR_NM             VARCHAR(50)    NOT NULL COMMENT '담당자명',
  CONSTRAINT pk_client_mgr PRIMARY KEY (CLIENT_ID, MGR_ID),
  CONSTRAINT fk_mgr_client FOREIGN KEY (CLIENT_ID) REFERENCES TB_CLIENT (CLIENT_ID)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='발주처담당자';

-- 프로젝트
CREATE TABLE TB_PRJ (
  PRJ_ID             CHAR(7)        NOT NULL COMMENT '프로젝트ID',
  PRJ_NM             VARCHAR(100)   NOT NULL COMMENT '프로젝트명',
  STRT_DT            DATE           NOT NULL COMMENT '시작일자',
  SCHD_END_DT        DATE           NOT NULL COMMENT '예정종료일자',
  END_DT             DATE           NULL COMMENT '종료일자',
  PRJ_STAT           VARCHAR(10)    NOT NULL COMMENT '프로젝트상태',
  CLIENT_ID          INT            NOT NULL COMMENT '발주처ID',
  MGR_ID             INT            NOT NULL COMMENT '담당자ID',
  CONSTRAINT pk_prj PRIMARY KEY (PRJ_ID),
  CONSTRAINT fk_prj_mgr FOREIGN KEY (CLIENT_ID, MGR_ID) REFERENCES TB_CLIENT_MGR (CLIENT_ID, MGR_ID),
  CONSTRAINT ck_prj_stat CHECK (PRJ_STAT IN ('진행','종료','중단','지연')),
  CONSTRAINT ck_prj_date CHECK (SCHD_END_DT >= STRT_DT AND (END_DT IS NULL OR END_DT >= STRT_DT)),
  CONSTRAINT ck_prj_end CHECK ((PRJ_STAT IN ('종료','중단') AND END_DT IS NOT NULL) OR (PRJ_STAT IN ('진행','지연') AND END_DT IS NULL))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='프로젝트';

-- 프로젝트참여
CREATE TABLE TB_PRJ_PTCP (
  EMP_ID             CHAR(7)        NOT NULL COMMENT '직원ID',
  PRJ_ID             CHAR(7)        NOT NULL COMMENT '프로젝트ID',
  ROLE_ID            VARCHAR(10)    NOT NULL COMMENT '직무ID',
  CONSTRAINT pk_prj_ptcp PRIMARY KEY (EMP_ID, PRJ_ID),
  CONSTRAINT fk_ptcp_emp FOREIGN KEY (EMP_ID) REFERENCES TB_DEV_EMP (EMP_ID),
  CONSTRAINT fk_ptcp_prj FOREIGN KEY (PRJ_ID) REFERENCES TB_PRJ (PRJ_ID),
  CONSTRAINT fk_ptcp_role FOREIGN KEY (ROLE_ID) REFERENCES TB_ROLE (ROLE_ID)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='프로젝트참여';

-- 프로젝트이력 (철수사유ID: 고도화 ①)
CREATE TABLE TB_PRJ_HIST (
  PRJ_HIST_ID        INT            NOT NULL AUTO_INCREMENT COMMENT '프로젝트이력ID',
  EMP_ID             CHAR(7)        NOT NULL COMMENT '직원ID',
  PRJ_ID             CHAR(7)        NOT NULL COMMENT '프로젝트ID',
  STRT_DT            DATE           NOT NULL COMMENT '시작일자',
  END_DT             DATE           NULL COMMENT '종료일자',
  WTHDR_RSN_ID       VARCHAR(10)    NULL COMMENT '철수사유ID',
  CONSTRAINT pk_prj_hist PRIMARY KEY (PRJ_HIST_ID),
  CONSTRAINT fk_hist_ptcp FOREIGN KEY (EMP_ID, PRJ_ID) REFERENCES TB_PRJ_PTCP (EMP_ID, PRJ_ID),
  CONSTRAINT fk_hist_rsn FOREIGN KEY (WTHDR_RSN_ID) REFERENCES TB_WTHDR_RSN (WTHDR_RSN_ID),
  CONSTRAINT ck_hist_date CHECK (END_DT IS NULL OR END_DT >= STRT_DT),
  CONSTRAINT ck_hist_rsn CHECK ((END_DT IS NULL AND WTHDR_RSN_ID IS NULL) OR (END_DT IS NOT NULL AND WTHDR_RSN_ID IS NOT NULL))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='프로젝트이력 (철수사유ID: 고도화 ①)';

-- 평가메모 (고도화 ①)
CREATE TABLE TB_EVAL_MEMO (
  MEMO_ID            INT            NOT NULL AUTO_INCREMENT COMMENT '메모ID',
  MEMO_CN            VARCHAR(1000)  NOT NULL COMMENT '메모내용',
  WRT_DTTM           DATETIME       NOT NULL COMMENT '작성일시',
  MOD_DTTM           DATETIME       NULL COMMENT '수정일시',
  WRTR_EMP_ID        CHAR(7)        NOT NULL COMMENT '작성자직원ID',
  TRGT_EMP_ID        CHAR(7)        NOT NULL COMMENT '대상자직원ID',
  PRJ_ID             CHAR(7)        NOT NULL COMMENT '프로젝트ID',
  CONSTRAINT pk_eval_memo PRIMARY KEY (MEMO_ID),
  CONSTRAINT fk_memo_wrtr FOREIGN KEY (WRTR_EMP_ID, PRJ_ID) REFERENCES TB_PRJ_PTCP (EMP_ID, PRJ_ID),
  CONSTRAINT fk_memo_trgt FOREIGN KEY (TRGT_EMP_ID, PRJ_ID) REFERENCES TB_PRJ_PTCP (EMP_ID, PRJ_ID),
  CONSTRAINT ck_memo_self CHECK (WRTR_EMP_ID <> TRGT_EMP_ID),
  CONSTRAINT ck_memo_mod CHECK (MOD_DTTM IS NULL OR MOD_DTTM >= WRT_DTTM)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='평가메모 (고도화 ①)';

-- 인력교체요청 (고도화 ②)
CREATE TABLE TB_STAFF_REPL_REQ (
  REPL_REQ_ID        INT            NOT NULL AUTO_INCREMENT COMMENT '교체요청ID',
  REQ_DT             DATE           NOT NULL COMMENT '요청일자',
  REQ_RSN            VARCHAR(500)   NOT NULL COMMENT '요청사유',
  PROC_STAT          VARCHAR(10)    NOT NULL DEFAULT '접수' COMMENT '처리상태',
  PROC_DT            DATE           NULL COMMENT '처리일자',
  REPL_TRGT_HIST_ID  INT            NOT NULL COMMENT '교체대상이력ID',
  SUCC_HIST_ID       INT            NULL COMMENT '후임이력ID',
  CLIENT_ID          INT            NOT NULL COMMENT '발주처ID',
