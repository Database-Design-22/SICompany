) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='철수사유';

-- 평가항목
CREATE TABLE TB_EVAL_ITEM (
  EVAL_ITEM_ID       VARCHAR(10)    NOT NULL COMMENT '평가항목ID',
  EVAL_ITEM_NM       VARCHAR(30)    NOT NULL COMMENT '평가항목명',
