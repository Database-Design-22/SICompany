-- 평가문항
CREATE TABLE TB_EVAL_QSTN (
  QSTN_ID            INT            NOT NULL AUTO_INCREMENT COMMENT '문항ID',
  QSTN_CN            VARCHAR(300)   NOT NULL COMMENT '문항내용',
  PM_USE_YN          CHAR(1)        NOT NULL COMMENT 'PM사용여부',
  PEER_USE_YN        CHAR(1)        NOT NULL COMMENT '동료사용여부',
  CUST_USE_YN        CHAR(1)        NOT NULL COMMENT '고객사용여부',
  EVAL_ITEM_ID       VARCHAR(10)    NOT NULL COMMENT '평가항목ID',
  CONSTRAINT pk_eval_qstn PRIMARY KEY (QSTN_ID),
  CONSTRAINT fk_qstn_item FOREIGN KEY (EVAL_ITEM_ID) REFERENCES TB_EVAL_ITEM (EVAL_ITEM_ID),
  CONSTRAINT ck_qstn_yn CHECK (PM_USE_YN IN ('Y','N') AND PEER_USE_YN IN ('Y','N') AND CUST_USE_YN IN ('Y','N') AND (PM_USE_YN = 'Y' OR PEER_USE_YN = 'Y' OR CUST_USE_YN = 'Y'))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='평가문항';

-- 평가문항별점수
CREATE TABLE TB_EVAL_QSTN_SCORE (
  EVAL_ID            INT            NOT NULL COMMENT '평가ID',
  QSTN_ID            INT            NOT NULL COMMENT '문항ID',
  SCORE              TINYINT        NOT NULL COMMENT '점수',
